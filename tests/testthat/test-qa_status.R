test_that("status follows hash changes, callee changes and self-review", {
  repo <- local_git_repo(list("R/a.R" = c("h <- function(x) x", "f <- function(x) h(x)"),
                              "_targets.R" = "list(tar_target(t1, f(1)))"), author = c("Ann", "ann@wig2.de"))
  set_git_user(repo, "Bob", "bob@wig2.de")
  for (i in c("function:h", "function:f", "target:t1")) suppressMessages(qa_review(i, "correct", path = repo))
  expect_true(all(qa_status(repo)$status == "correct"))
  expect_message(qa_check(repo), "QA check passed: 3 items reviewed")
  commit_as(repo, "R/a.R", c("h <- function(x) x * 2", "f <- function(x) h(x)"), author = c("Ann", "ann@wig2.de"))
  st <- qa_status(repo)
  expect_equal(st$status[st$id == "function:h"], "changed")
  expect_equal(st$status[st$id == "function:f"], "check_again")
  expect_error(suppressMessages(qa_check(repo)), "1 changed")
  expect_message(try(qa_check(repo), silent = TRUE), "check again: function:f")
  set_git_user(repo, "Ann", "ann@wig2.de")
  suppressMessages(qa_review("function:h", "correct", path = repo))
  st <- qa_status(repo)
  expect_true(st$self_reviewed[st$id == "function:h"])
  expect_error(suppressMessages(qa_check(repo)), "self-reviewed")
})

test_that("unreviewed, wrong and questionable are gated", {
  repo <- local_git_repo(list("R/a.R" = c("h <- function(x) x", "f <- function(x) x"), "_targets.R" = "list(tar_target(t1, f(1)))"))
  set_git_user(repo, "Bob", "bob@wig2.de")
  expect_error(qa_check(repo), "QA check failed: 3 unreviewed")
  suppressMessages({
    qa_review("h", "questionable", "hm", path = repo)
    qa_review("f", "correct", path = repo)
    qa_review("t1", "correct", path = repo)
  })
  expect_message(qa_check(repo), "passed")
  expect_error(qa_check(repo, allow_questionable = FALSE), "1 questionable")
  suppressMessages(qa_review("h", "wrong", "no", path = repo))
  expect_error(qa_check(repo), "1 wrong")
  expect_output(print(qa_status(repo)), "wrong")
})

test_that("qa_status works without git", {
  p <- local_project(list("R/a.R" = "f <- function() 1", "_targets.R" = "list()"))
  st <- qa_status(p)
  expect_equal(st$status, c("unreviewed", "unreviewed"))
  expect_true(all(is.na(st$last_author)))
  expect_error(qa_status(p, base = "main"), "git")
})

test_that("changed_vs_base and orphans", {
  repo <- local_git_repo(list("R/a.R" = "f <- function() 1", "_targets.R" = "list()"))
  git_run(repo, c("checkout", "-b", "dev/x"))
  commit_as(repo, "R/a.R", c("f <- function() 2", "g <- function() 3"))
  st <- qa_status(repo, base = "main")
  expect_equal(st$changed_vs_base[match(c("function:f", "function:g"), st$id)], c(TRUE, TRUE))
  set_git_user(repo, "Zed", "zed@wig2.de"); suppressMessages(qa_review("g", "correct", path = repo))
  commit_as(repo, "R/a.R", "f <- function() 2")
  expect_equal(qa_status(repo, orphans = TRUE)$item, "function:g")
})
