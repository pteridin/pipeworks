test_that("report data reflects status and drafts are marked", {
  repo <- reviewed_repo()
  d <- report_data(repo)
  expect_true(d$passed)
  expect_equal(d$counts$items, 6)
  expect_equal(d$counts$questionable, 1)
  expect_equal(d$counts$correct, 5)
  expect_equal(d$counts$wrong_open, 0)
  expect_equal(unlist(d$analysts), "Ann")
  expect_equal(unlist(d$reviewers), "Bob")
  expect_equal(d$ref, "main")
  expect_equal(nchar(d$commit), 7)
  commit_as(repo, "R/a.R", "f <- function() 99")
  d2 <- report_data(repo)
  expect_false(d2$passed)
  expect_gt(d2$counts$wrong_open, 0)
})

test_that("blocks, edges and items carry what the template needs", {
  d <- report_data(reviewed_repo())
  expect_setequal(vapply(d$blocks, `[[`, "", "block"), c("R/a.R", "R/b.R", "_targets.R"))
  a <- Filter(function(b) b$block == "R/a.R", d$blocks)[[1]]
  g <- Filter(function(i) i$id == "function:g", a$items)[[1]]
  expect_equal(g$verdict, "questionable")
  expect_equal(g$reviewer, "Bob")
  expect_equal(g$title, "Add one to the input")
  expect_match(g$comment, "Edge case")
  expect_equal(nchar(g$hash7), 7)
  edges <- vapply(d$edges, function(e) paste(e$from, e$to), "")
  expect_true("R/a.R R/b.R" %in% edges)
  expect_true("R/b.R _targets.R" %in% edges)
  expect_false(any(vapply(d$edges, function(e) e$from == e$to, NA)))
})

test_that("history lists merges that brought in review entries", {
  repo <- local_git_repo(list("R/a.R" = "f <- function() 1", "_targets.R" = "list(tar_target(t1, f()))"))
  git_run(repo, c("checkout", "-q", "-b", "dev/x"))
  set_git_user(repo, "Bob", "bob@wig2.de")
  suppressMessages({
    qa_review("function:f", "correct", path = repo)
    qa_review("target:t1", "correct", path = repo)
  })
  git_cmd(repo, "add", "-A")
  git_cmd(repo, "-c", "commit.gpgsign=false", "commit", "-q", "-m", shQuote("reviews"))
  git_run(repo, c("checkout", "-q", "main"))
  commit_as(repo, "README.md", "hello")
  git_cmd(repo, "-c", "commit.gpgsign=false", "merge", "-q", "--no-ff", "-m", shQuote("Merge branch 'dev/x' into 'main'"), "dev/x")
  h <- report_data(repo)$history
  expect_length(h, 1)
  expect_equal(h[[1]]$branch, "dev/x")
  expect_equal(h[[1]]$items, 2)
  expect_equal(h[[1]]$rounds, 1)
  expect_match(h[[1]]$merged, "^\\d{4}-\\d{2}-\\d{2}$")
  expect_length(report_data(reviewed_repo())$history, 0)
})

test_that("a PDF is rendered, final refuses drafts", {
  skip_if(Sys.which("quarto") == "")
