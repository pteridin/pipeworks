test_that("PDF text: confirmation when passed, draft banner and open items otherwise", {
  skip_if(Sys.which("quarto") == "" || Sys.which("pdftotext") == "")
  withr::local_options(pipeworks.organisation = "WIG2 GmbH")
  txt <- function(pdf) paste(system2("pdftotext", c("-layout", shQuote(pdf), "-"), stdout = TRUE), collapse = " ")
  flat <- function(x) gsub("\\s+", " ", x)
  repo <- reviewed_repo()
  ok <- flat(txt(qa_report(repo, output = file.path(tempdir(), "ok.pdf"), title = "Survey QA")))
  expect_match(ok, "WIG2 GmbH", fixed = TRUE)
  expect_match(ok, "Survey QA", fixed = TRUE)
  expect_match(ok, "Every function and target definition in this code version was reviewed by a second analyst", fixed = TRUE)
  expect_match(ok, "generated digitally and is valid without signature", fixed = TRUE)
  expect_false(grepl("DRAFT", ok, fixed = TRUE))
  expect_match(ok, "Edge case x = NA not handled", fixed = TRUE)
  signed <- flat(txt(qa_report(repo, output = file.path(tempdir(), "sig.pdf"), signatures = TRUE)))
  expect_false(grepl("valid without signature", signed, fixed = TRUE))
  expect_match(signed, "Signature", fixed = TRUE)

  commit_as(repo, "R/a.R", c("f <- function() 99", "g <- function(x) x + f()"))
  draft <- flat(txt(qa_report(repo, output = file.path(tempdir(), "draft.pdf"))))
  expect_match(draft, "DRAFT – QA incomplete", fixed = TRUE)
  expect_match(draft, "function:f", fixed = TRUE)
  expect_false(grepl("Every function and target definition", draft, fixed = TRUE))
})

test_that("ref reports an older commit and removes its worktree", {
  skip_if(Sys.which("quarto") == "")
  repo <- reviewed_repo()
  git_run(repo, c("tag", "v1"))
  commit_as(repo, "R/a.R", "f <- function() 99")
  expect_false(report_data(repo)$passed)
  out <- qa_report(repo, ref = "v1", output = file.path(tempdir(), "v1.pdf"), final = TRUE)
  expect_true(file.exists(out))
  expect_length(git_run(repo, c("worktree", "list")), 1)
})

